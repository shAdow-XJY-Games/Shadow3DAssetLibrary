def earclip(poly):
    order=list(range(len(poly)));out=[]
    def cr(a,b,c):return (b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0])
    assert area(poly)>0
    while len(order)>3:
        for k,b in enumerate(order):
            a=order[k-1];c=order[(k+1)%len(order)]
            if cr(poly[a],poly[b],poly[c])<=1e-13:continue
            if any(all(cr(poly[x],poly[y],poly[q])>=-1e-13 for x,y in [(a,b),(b,c),(c,a)]) for q in order if q not in [a,b,c]):continue
            out.append((a,b,c));order.pop(k);break
        else:raise AssertionError('Ear clipping failed; no geometry fallback permitted')
    out.append(tuple(order));return out

